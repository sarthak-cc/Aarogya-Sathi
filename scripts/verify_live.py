"""Live verification against the REAL providers (uses the keys in .env). Not mocked.

    cd backend && python ../scripts/verify_live.py            # Hindi + English + Assamese
    cd backend && python ../scripts/verify_live.py hi-IN bn-IN

For each language it runs the real pipeline end to end on questions that are not
in any dataset, plus an emergency phrase, and a speech round-trip (real TTS audio
fed into real STT) where a voice exists. Results are written to
backend/app/data/verification.json (read by the language picker) and
docs/VERIFICATION.md. A language is marked passed only if every check passed.
Machine checks cannot judge language quality: have native speakers review the
answers printed here before claiming a language works well.
"""
from __future__ import annotations

import asyncio
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app import audio_store, config, facilities, languages, pipeline, sessions  # noqa: E402
from app.providers import ProviderError, stt  # noqa: E402

QUESTIONS = {
    "en-IN": ("Why do my knees hurt when the weather turns cold?", "My uncle suddenly cannot breathe and his lips are blue"),
    "hi-IN": ("बारिश के मौसम में पैरों में खुजली क्यों होती है?", "मेरे पति के सीने में दर्द है और पसीना आ रहा है"),
    "as-IN": ("জাৰকালি মোৰ ছালখন কিয় শুকান হয়?", "মোৰ দেউতাৰ বুকুৰ বিষ হৈছে"),
    "bn-IN": ("শীতকালে ঠোঁট ফাটে কেন?", "আমার মা অজ্ঞান হয়ে গেছেন"),
    "ne-IN": ("जाडोमा छाला किन सुक्खा हुन्छ?", "मेरो बुबालाई सास फेर्न गाह्रो भयो"),
    "brx-IN": ("", ""),
    "mni-IN": ("", ""),
}
VERIFY_FILE = languages.VERIFICATION_FILE
REPORT = ROOT / "docs" / "VERIFICATION.md"


def check(results: dict, name: str, ok: bool, detail: str = "") -> None:
    results[name] = {"passed": bool(ok), "detail": detail[:300]}
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}: {detail[:160]}")


async def verify(code: str) -> dict:
    lang = languages.get(code)
    q, emergency_q = QUESTIONS.get(code, ("", ""))
    print(f"\n== {lang.name} ({code})")
    results: dict = {}
    if not q:
        check(results, "sample_questions", False, "No native sample question yet: add one with a native speaker.")
        return results
    conv = sessions.create(code)

    turn = await pipeline.ask(conv, q)
    ans = turn.get("answer") or {}
    check(results, "llm_answer", turn["error"] is None and ans.get("source") == "llm",
          ans.get("english") or json.dumps(turn["error"]))
    if code != "en-IN":
        check(results, "translation_in", bool(turn["english"]), turn["english"] or "")
        check(results, "answer_in_language", ans.get("lang") == code and not ans.get("language_note"),
              ans.get("text", ""))
    if ans:
        print(f"     Q: {q}\n     A: {ans.get('text')}")
    voice = turn.get("voice") or {}
    has_voice = bool(languages.capability(lang)["speech_output"])
    if turn["error"]:
        results["voice_output"] = {"passed": None, "detail": "Not reached: the answer step failed."}
    elif has_voice:
        check(results, "voice_output", bool(voice.get("audio_url")), voice.get("provider") or voice.get("note") or "")
    else:
        results["voice_output"] = {"passed": None, "detail": "No voice provider for this language (not counted)."}
        print("  [ -- ] voice_output: none configured for this language")

    em = await pipeline.ask(conv, emergency_q)
    check(results, "emergency_detected", em["triage"]["level"] == "emergency" and em["triage"]["source"] == "rules",
          f"{em['triage']['level']} via {em['triage']['source']}")

    if has_voice and voice.get("audio_url"):  # round-trip: real synthesized speech into real STT
        clip = audio_store.get(voice["audio_url"].rsplit("/", 1)[-1])
        try:
            heard = await stt.transcribe(clip[0], "check.wav", clip[1], code)
            check(results, "speech_input", len(heard["text"]) > 5, f"{heard['provider']}: {heard['text']}")
        except ProviderError as exc:
            check(results, "speech_input", False, exc.public()["message"])
    elif languages.capability(lang)["speech_input"]:
        results["speech_input"] = {"passed": None, "detail": "Needs a real recording (no voice to round-trip)."}
        print("  [ -- ] speech_input: record a real question in the browser to check")
    return results


async def main(codes: list[str]) -> None:
    config.reload_settings()
    print("Providers:", json.dumps(config.settings.provider_status(), indent=1))
    store = languages.verification()
    lines = [f"# Live verification ({date.today().isoformat()})", "",
             f"Model: `{config.settings.llm_model}`. Generated by `scripts/verify_live.py` against the real providers.",
             "Machine checks only: native speakers must still review answer quality.", "",
             "| Language | Checks passed | Failed / not checked |", "|---|---|---|"]
    for code in codes:
        res = await verify(code)
        counted = {k: v for k, v in res.items() if v["passed"] is not None}
        passed = bool(counted) and all(v["passed"] for v in counted.values())
        store[code] = {"passed": passed, "date": date.today().isoformat(), "checks": res}
        ok = [k for k, v in res.items() if v["passed"]]
        bad = [f"{k}" + ("" if v["passed"] is False else " (n/a)") for k, v in res.items() if not v["passed"]]
        lines.append(f"| {languages.get(code).name} | {', '.join(ok) or '-'} | {', '.join(bad) or '-'} |")

    print("\n== Facilities (OpenStreetMap, Jalukbari, Guwahati)")
    found = await facilities.find(26.1430, 91.6600, emergency=True)
    fac_ok = bool(found["facilities"]) and not found["error"]
    print(f"  [{'PASS' if fac_ok else 'FAIL'}] {len(found['facilities'])} found; error={found['error']}")
    for f in found["facilities"][:3]:
        print(f"     {f['distance_km']} km  {f['name']}  ({f['emergency_label']})")
    lines += ["", f"Facilities near Jalukbari: {'PASS' if fac_ok else 'FAIL'} ({len(found['facilities'])} from OpenStreetMap)."]

    VERIFY_FILE.write_text(json.dumps(store, ensure_ascii=False, indent=1), encoding="utf-8")
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nWrote {VERIFY_FILE.relative_to(ROOT)} and {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    asyncio.run(main(sys.argv[1:] or ["hi-IN", "en-IN", "as-IN"]))
