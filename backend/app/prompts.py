_machine_cache: dict[tuple[str, str], str] = {}


def language_menu() -> str:
    parts = [f"For {lang.name}, press {lang.keypad}." for lang in languages.REGISTRY.values() if lang.keypad]
    parts.append(f"For Khasi, Garo, Mizo, Kokborok or Nagamese, press {languages.OTHER_LANGUAGES_DIGIT}.")
    return " ".join(parts)


async def get(key: str, lang_code: str, **fmt) -> dict:
    """Return {'text', 'lang', 'source'}; source = hand | machine | english_fallback."""
    if lang_code == "en-IN":
        return {"text": EN[key].format(**fmt), "lang": "en-IN", "source": "hand"}
    hand = HAND.get(lang_code, {})
    if key in hand:
        return {"text": hand[key].format(**fmt), "lang": lang_code, "source": "hand"}

    if fmt and key != "readback":
        # Translate the filled sentence: machine translation can mangle {placeholders}.
        from .providers import ProviderError, translate

        filled = EN[key].format(**fmt)
        try:
            translated = await translate.from_english(filled, lang_code)
        except ProviderError:  # a translation outage must not break a call
            translated = None
        if translated:
            return {"text": translated, "lang": lang_code, "source": "machine"}
        return {"text": filled, "lang": "en-IN", "source": "english_fallback"}

    cache_key = (key, lang_code)
    if cache_key not in _machine_cache:
        from .providers import translate  # local import avoids a cycle

        translated = await translate.from_english(EN[key], lang_code)
        if translated is not None:
            _machine_cache[cache_key] = translated
    if cache_key in _machine_cache:
        template = _machine_cache[cache_key]
        try:
            text = template.format(**fmt) if fmt else template
        except (KeyError, IndexError, ValueError):
            text = template
        # Machine translation may drop the {text} placeholder; keep the caller's words audible.
        if fmt.get("text") and fmt["text"] not in text:
            text = f"“{fmt['text']}” — {text.replace('{text}', '')}"
        return {"text": text, "lang": lang_code, "source": "machine"}
    return {"text": EN[key].format(**fmt), "lang": "en-IN", "source": "english_fallback"}
